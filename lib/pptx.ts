export async function buildPptxFromJpegs(
  images: Array<{ bytes: Uint8Array }>,
  options: { title: string; widthPx: number; heightPx: number }
): Promise<Blob> {
  if (images.length === 0) {
    throw new Error("No slides to export.");
  }
  const widthIn = Math.max(4, Math.min(20, options.widthPx / 96));
  const heightIn = Math.max(4, Math.min(20, options.heightPx / 96));
  const widthEmu = Math.round(widthIn * EMU);
  const heightEmu = Math.round(heightIn * EMU);
  const zip = new JSZip();
  zip.file("[Content_Types].xml", contentTypes(images.length));
  zip.file("_rels/.rels", rootRels());
  zip.file("docProps/core.xml", coreXml(options.title));
  zip.file("docProps/app.xml", appXml(images.length));
  zip.file("ppt/presentation.xml", presentationXml(images.length, widthEmu, heightEmu));
  zip.file("ppt/_rels/presentation.xml.rels", presentationRels(images.length));
  zip.file("ppt/theme/theme1.xml", themeXml());
  zip.file("ppt/slideMasters/slideMaster1.xml", slideMasterXml());
  zip.file("ppt/slideMasters/_rels/slideMaster1.xml.rels", slideMasterRels());
  zip.file("ppt/slideLayouts/slideLayout1.xml", slideLayoutXml());
  zip.file("ppt/slideLayouts/_rels/slideLayout1.xml.rels", slideLayoutRels());

  images.forEach((image, index) => {
    const n = index + 1;
    zip.file(`ppt/slides/slide${n}.xml`, slideXml(widthEmu, heightEmu));
    zip.file(`ppt/slides/_rels/slide${n}.xml.rels`, slideRels(n));
    zip.file(`ppt/media/image${n}.jpeg`, image.bytes);
  });

  return zip.generateAsync({ type: "blob", mimeType: "application/vnd.openxmlformats-officedocument.presentationml.presentation" });
}
